// Regenerates packages/protocol/src/generated from the Rust types (ts-rs).
// The output is committed; the gate fails if it drifts from the Rust source.
import { execFileSync } from "node:child_process";
import { readdirSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "packages/protocol/src/generated");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

execFileSync("cargo", ["test", "--workspace", "--quiet", "export_bindings"], {
  cwd: root,
  stdio: ["ignore", "ignore", "inherit"],
  env: { ...process.env, TS_RS_EXPORT_DIR: out, TANDEM_FAKE_KEYCHAIN: "1" },
});

const files = readdirSync(out)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .sort();
const header = "// Generated by scripts/gen-protocol.ts from Rust types. Do not edit.\n";
writeFileSync(
  join(out, "index.ts"),
  header + files.map((f) => `export type * from "./${f.replace(/\.ts$/, "")}";`).join("\n") + "\n",
);
console.log(`protocol: ${files.length} types`);
